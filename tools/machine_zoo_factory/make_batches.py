"""Build <job>/BATCHES/batches.txt from a domain list (deterministic; run once, keep the output with the job).

    python3 make_batches.py --job myjob --domains examples/domains_example.txt [--salt my-split-v1] [--dev-every 5]

domains file: one `domain_id | one-line machine description` per line ('#' comments). It is copied to
<job>/BATCHES/domains.txt. Domains are sorted by sha256('<salt>|' + domain_id); with --dev-every k, positions 0, k,
2k, ... become DEV batches (whole domains you never train on: a held-back split of your own), the rest TRAIN.
One batch = one domain. TRAIN batches rotate the train plans (default A/B/C, 6 slots each), DEV batches use the dev
plan (default D, 4 slots); plans: famgate/jobkit.py DEFAULT_PLANS or <job>/BATCHES/plans.json.
Pick your salt BEFORE looking at any family, and never change it afterwards (it decides the dev split).
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from famgate import jobkit  # noqa: E402

DOMAIN_RE = re.compile(r"[a-z][a-z0-9_]{2,40}")


def read_domains(path: str) -> list[tuple[str, str]]:
    doms, seen = [], set()
    with open(path) as f:
        lines = f.read().splitlines()
    for ln in lines:
        if not ln.strip() or ln.lstrip().startswith("#"):
            continue
        d, _, desc = (x.strip() for x in ln.partition("|"))
        if not DOMAIN_RE.fullmatch(d):
            raise SystemExit(f"bad domain_id {d!r} (must match {DOMAIN_RE.pattern})")
        if d in seen:
            raise SystemExit(f"duplicate domain_id {d!r}")
        seen.add(d)
        doms.append((d, desc))
    return doms


def make(job: str, domains_path: str | None = None, salt: str = "mzf-split-v1", dev_every: int = 5) -> list[str]:
    P = jobkit.paths(job)
    os.makedirs(P["BATCHES"], exist_ok=True)
    os.makedirs(P["FAMILIES"], exist_ok=True)
    if domains_path and os.path.abspath(domains_path) != os.path.abspath(P["domains"]):
        shutil.copyfile(domains_path, P["domains"])
    if not os.path.exists(P["domains"]):
        raise SystemExit("no domain list: pass --domains FILE (copied to BATCHES/domains.txt)")
    plans, rot = jobkit.load_plans(job)
    train_plans, dev_plan = list(rot["train"]), rot["dev"]
    for k in train_plans + [dev_plan]:
        if k not in plans:
            raise SystemExit(f"plan {k!r} not defined")
    doms = read_domains(P["domains"])
    doms.sort(key=lambda x: hashlib.sha256(f"{salt}|{x[0]}".encode()).hexdigest())
    out = ["# bid | domain_id | split (train | dev = held-back domains, never trained) | plan | description",
           f"# generated by make_batches.py from domains.txt; order = sha256(\"{salt}|\"+domain_id) ascending; "
           f"dev every {dev_every or 'never'}"]
    k = 0
    for pos, (d, desc) in enumerate(doms):
        if dev_every and pos % dev_every == 0:
            split, plan = "dev", dev_plan
        else:
            split, plan = "train", train_plans[k % len(train_plans)]
            k += 1
        out.append(f"b{pos + 1:02d} | {d} | {split} | {plan} | {desc}")
    with open(P["batches"], "w") as f:
        f.write("\n".join(out) + "\n")
    n_dev = len(doms) - k
    print(f"{len(doms)} batches: {n_dev} dev, {k} train -> BATCHES/batches.txt")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--job", default=".", help="job folder (default: current directory)")
    ap.add_argument("--domains", default=None, help="domain list (default: <job>/BATCHES/domains.txt)")
    ap.add_argument("--salt", default="mzf-split-v1", help="split salt; fix it before any family exists")
    ap.add_argument("--dev-every", type=int, default=5, help="every k-th domain is a DEV batch (0 = no dev split)")
    a = ap.parse_args(argv)
    P = jobkit.paths(a.job)
    if os.path.exists(P["batches"]) and os.path.isdir(P["REPORTS"]) and os.listdir(P["REPORTS"]):
        raise SystemExit("BATCHES/batches.txt exists and the job has reports: the split is frozen; not rewriting it")
    make(a.job, a.domains, a.salt, a.dev_every)
    return 0


if __name__ == "__main__":
    sys.exit(main())
